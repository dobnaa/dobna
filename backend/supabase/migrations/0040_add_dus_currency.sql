-- 0040_add_dus_currency.sql
-- افزودن DUS (Dobna Unit) به جدول currencies به‌عنوان یک ارز کامل دوبنا
--
-- DUS پابه‌پای دلار است (۱ DUS = ۱ USD ثابت، نه شناور). به همین دلیل
-- price_usd آن همیشه ۱.۰۰ می‌ماند و نیازی به به‌روزرسانی از API قیمت ندارد.
-- اضافه شدن این ردیف باعث می‌شود fn_get_exchange_rate برای DUS هم به‌درستی
-- کار کند، و DUS بتواند دقیقاً مثل بقیه‌ی ارزها در گروه/چالش/دوئل استفاده شود.
-- ======================================================
INSERT INTO public.currencies (code, name, type, price_usd, is_active)
VALUES ('DUS', 'Dobna Unit', 'internal', 1.00, true)
ON CONFLICT (code) DO UPDATE SET price_usd = 1.00, is_active = true;

-- نکته: اگر جدول currencies ستون‌های دقیقاً با این نام‌ها ندارد (مثلاً 'type'
-- یا 'is_active' وجود ندارد)، لطفاً ستون‌های واقعی را با ما در میان بگذارید
-- تا این INSERT با schema واقعی هماهنگ شود — ساختار دقیق این جدول در این
-- مکالمه هنوز دیده نشده است.
